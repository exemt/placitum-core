#!/bin/sh
#
# Правила удаления в бакетах архива: по одному на срок, фильтр по тегу
# waf-retain-ttl. Тег ставит агент значением, которое назвал маршрут
# (waf_archive request ... ttl=), в секундах и без единицы измерения.
#
# Тегом, а не префиксом ключа: префикс разрезал бы пространство имён, и перебор
# объектов за инцидент стоил бы листинга на каждый срок. Имя объекта теперь
# зависит только от даты, узла и ray (docs/deployment.md).
#
# Ставятся здесь, а не агентом: срок объекта агент лишь передаёт, а удаляет его
# владелец бакета. Ему же отвечать на регуляторное "удалите все тела".
#
# Правила нужны не только для уборки. Хранилище называет срок объекта в
# x-amz-expiration тем же ответом на PUT, агент переносит его в локатор записи,
# и карточка инцидента по нему решает, идти ли за объектом вообще. Без правил
# срока в записи нет -- и поиск ходит в архив за тем, чего там уже нет.
#
# Идемпотентно: import заменяет конфигурацию бакета целиком.

set -e

for bucket in waf-headers waf-args waf-bodies; do
    mc mb --ignore-existing "waf/$bucket"
    mc ilm import "waf/$bucket" < /etc/waf/lifecycle.json
done

mc ilm rule ls waf/waf-bodies
